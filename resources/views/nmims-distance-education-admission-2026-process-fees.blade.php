        <!-- SECTION 4 -->
        <h2 id="eligibility"><span class="h2-number">4</span> Eligibility Criteria: Are You Eligible?</h2>

        <h3>For UG Programs (BBA, B.Com)</h3>
        <ul style="padding-left: 22px; margin-bottom: 16px;">
            <li style="margin-bottom: 8px; color: #444;">Must have passed Class 12 (10+2) from a recognised board</li>
            <li style="margin-bottom: 8px; color: #444;">Minimum 50% marks (45% for reserved category candidates)</li>
            <li style="margin-bottom: 8px; color: #444;">No specific upper age limit</li>
            <li style="color: #444;">No entrance exam required</li>
        </ul>

        <h3>For PG Programs (MBA, PGDBM)</h3>
        <ul style="padding-left: 22px; margin-bottom: 16px;">
            <li style="margin-bottom: 8px; color: #444;">Bachelor's degree in any discipline from a recognised
                university</li>
            <li style="margin-bottom: 8px; color: #444;">Minimum 50% in qualifying degree</li>
            <li style="margin-bottom: 8px; color: #444;">For MBA-WX: minimum 3 years of work experience in a managerial
                role (mandatory)</li>
            <li style="color: #444;">No entrance exam (CAT/MAT) required — merit-based admission</li>
        </ul>

        <div class="callout callout-remember">
            <div class="callout-icon">🔔</div>
            <div class="callout-body">
                <strong>Major Point to Remember</strong>
                <p>NMIMS CDOE does not conduct any entrance examination for its distance and online programs. Admission
                    is purely merit-based. This makes it one of the most accessible quality programs in the country.</p>
            </div>
