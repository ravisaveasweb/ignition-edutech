        <h2 id="how-to-apply"><span class="h2-number">7</span> How to Apply: Step-by-Step Process</h2>

        <ul class="steps-list">
            <li class="step-item">
                <div class="step-num">1</div>
                <div class="step-content">
                    <h4>Visit the Official NMIMS CDOE Website</h4>
                    <p>Go directly to the official portal. Do not use any third-party websites or unverified links.</p>
                    <a href="https://online.nmims.edu" class="step-url" target="_blank">online.nmims.edu</a>
                </div>
            </li>
            <li class="step-item">
                <div class="step-num">2</div>
                <div class="step-content">
                    <h4>Select Your Desired Program</h4>
                    <p>Browse the list of available programs. Read program details, curriculum, specialisations, and
                        eligibility carefully. NMIMS offers programs across 18 specialisation areas.</p>
                </div>
            </li>
            <li class="step-item">
                <div class="step-num">3</div>
                <div class="step-content">
                    <h4>Register as a New User</h4>
                    <p>Click "Apply Now" for your chosen program. Create an account using your name, mobile number, and
                        email ID. You'll receive login credentials via email and SMS.</p>
                </div>
            </li>
            <li class="step-item">
                <div class="step-num">4</div>
                <div class="step-content">
                    <h4>Fill the Application Form</h4>
                    <p>Log in and fill all details accurately — personal info, educational qualifications, work
                        experience (if applicable), and contact information. Double-check before proceeding.</p>
                </div>
            </li>
            <li class="step-item">
                <div class="step-num">5</div>
                <div class="step-content">
                    <h4>Upload All Required Documents</h4>
                    <p>Upload scanned copies of all required documents. Ensure every file is clear, complete, and within
                        the permitted size limit.</p>
                </div>
            </li>
            <li class="step-item">
                <div class="step-num">6</div>
                <div class="step-content">
                    <h4>Pay the Application Fee — ₹1,200</h4>
                    <p>Pay online using debit card, credit card, net banking, or UPI. Save the confirmation receipt
                        immediately — you'll need it for future reference.</p>
                </div>
            </li>
            <li class="step-item">
                <div class="step-num">7</div>
                <div class="step-content">
                    <h4>Submit and Track Your Application</h4>
                    <p>After payment, submit your application. You'll receive a confirmation email with your application
                        number. Use it to track your admission status on the portal.</p>
                </div>
            </li>
            <li class="step-item">
                <div class="step-num">8</div>
                <div class="step-content">
                    <h4>Await Confirmation and Onboarding</h4>
                    <p>Once documents are verified and your application is accepted, you'll receive further
                        communication regarding programme onboarding, LMS access, and the academic calendar.</p>
                </div>
            </li>
        </ul>

        <div class="callout callout-remember">
            <div class="callout-icon">🔔</div>
            <div class="callout-body">
                <strong>Major Point to Remember</strong>
                <p>The entire admission process is 100% online. You do not need to visit any campus or submit physical
                    documents. Everything — from form filling to fee payment — happens on the NMIMS CDOE official
                    portal.</p>
            </div>
